  function run() {
    var text = $("#txt").value.trim();
    if (!text) { $("#res").innerHTML = "<div class='res'><p>Type a product first.</p></div>"; return; }
    py.globals.set("_t", text);
    var o = JSON.parse(py.runPython("driver.suggest(_t)"));
    if (!o.candidates.length) { $("#res").innerHTML = "<div class='res'><p class='big'>Not sure: none of those words appear in the tariff schedule.</p><p>Try describing what it is and what it's made of.</p></div>"; return; }
    var c0 = o.candidates[0];
    function lineHtml(c) {
      if (!c.line) return "";
      return "<div style='margin-top:6px'><code>" + esc(c.line.code) + "</code> · general duty " + esc(c.line.general || "see higher line") + (c.line.units ? " · unit " + esc(c.line.units) : "") +
        "<div class='path'>" + c.line.path.map(function (p) { return "<span>" + esc(p) + "</span>"; }).join("") + "</div></div>";
    }
    var head = o.sure
      ? "<span class='pill ok'>suggested</span> <span class='big'>Heading " + esc(c0.heading) + "</span><p style='margin-top:6px'>" + esc(c0.heading_text) + "</p>" + lineHtml(c0)
      : "<span class='pill warn'>not sure</span> <span class='big'>Check these with a broker</span><p style='margin-top:6px'>It won't pick one because " + esc(o.reason) + ".</p>";
    var others = o.candidates.slice(o.sure ? 1 : 0).map(function (c) {
      return "<div class='case'><b>Heading " + esc(c.heading) + "</b> <span class='dimc'>(score " + c.score.toFixed(2) + ")</span><div class='q'>" + esc(c.heading_text) + "</div>" + lineHtml(c) + "</div>";
    }).join("");
    $("#res").innerHTML = "<div class='res'>" + head +
      (others ? "<h3 style='margin-top:14px'>" + (o.sure ? "Runners-up" : "Candidates") + "</h3>" + others : "") +
      (o.synonyms_used.length ? "<p style='font-size:.84rem;margin-top:10px'>Added schedule words for: " + esc(o.synonyms_used.join(", ")) + ".</p>" : "") +
      "<p style='font-size:.82rem'>Duty shown is the base general rate only; additional chapter 99 duties aren't included.</p></div>";
  }

